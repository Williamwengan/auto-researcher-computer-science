#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description="Convert generic smoke-test metrics into bounded claims.")
    parser.add_argument("--metrics", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    metrics = json.loads(args.metrics.read_text(encoding="utf-8"))
    text = f"""# Generic Result-to-Claim Report

## Scope

This report is generated by a generic execution smoke runner for an unfamiliar research direction.
It verifies that the workflow can complete the execution interface, artifact generation, evaluation,
and claim-boundary steps. It is **not** evidence of domain benchmark performance.

## Supported claims

1. The system can transform an unfamiliar final idea into a runnable smoke-test workspace.
   - workflow_completion_rate = {metrics.get('workflow_completion_rate')}
   - tool_success_rate = {metrics.get('tool_success_rate')}

2. The system preserves claim boundaries for tasks without a real domain runner.
   - claim_boundary_ok = {metrics.get('claim_boundary_ok')}

3. The proposed workflow scaffold improves over a direct-plan scaffold on execution-readiness proxies.
   - plan_specificity_delta = {metrics.get('plan_specificity_delta')}
   - artifact_readiness_delta = {metrics.get('artifact_readiness_delta')}
   - risk_control_delta = {metrics.get('risk_control_delta')}

## Not claimed

- No domain SOTA result is claimed.
- No real dataset benchmark is claimed unless a task-specific runner is implemented.
"""
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"Saved: {args.output}")


if __name__ == "__main__":
    main()
